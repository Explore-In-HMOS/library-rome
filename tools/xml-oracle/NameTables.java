// Writes oh_rome/src/main/ets/xml/XmlNameChars.ets: the XML 1.0 and 1.1 name characters of the JDK's Xerces
// (XMLChar follows XML 1.0 4th edition, XML11Char follows XML 1.1), and its public identifier characters.
// From the repo root, on Temurin 17.0.17+10:
//   java --add-exports java.xml/com.sun.org.apache.xerces.internal.util=ALL-UNNAMED tools/xml-oracle/NameTables.java
import com.sun.org.apache.xerces.internal.util.XML11Char;
import com.sun.org.apache.xerces.internal.util.XMLChar;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.function.IntPredicate;

public class NameTables {
    // Inclusive [start, end] code point ranges.
    static List<int[]> ranges(IntPredicate p) {
        List<int[]> out = new ArrayList<>();
        int c = 0;
        while (c <= 0x10FFFF) {
            if (!p.test(c)) {
                c++;
                continue;
            }
            int start = c;
            while (c + 1 <= 0x10FFFF && p.test(c + 1)) {
                c++;
            }
            out.add(new int[] {start, c});
            c++;
        }
        return out;
    }

    static String array(List<int[]> ranges) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < ranges.size(); i++) {
            sb.append(i % 6 == 0 ? "\n  " : " ");
            sb.append(String.format("0x%x, 0x%x,", ranges.get(i)[0], ranges.get(i)[1]));
        }
        return sb.append("\n]").toString();
    }

    static String u(int c) {
        return String.format("\\u%04X", c);
    }

    // A sticky regex over UTF-16 code units; supplementary ranges must cover whole high-surrogate blocks.
    static String run(List<int[]> ranges) {
        StringBuilder bmp = new StringBuilder();
        List<String> pairs = new ArrayList<>();
        for (int[] r : ranges) {
            if (r[1] <= 0xFFFF) {
                bmp.append(u(r[0])).append(r[0] == r[1] ? "" : "-" + u(r[1]));
            } else if (r[0] >= 0x10000 && r[0] % 0x400 == 0 && (r[1] + 1) % 0x400 == 0) {
                pairs.add("[" + u(Character.highSurrogate(r[0])) + "-" + u(Character.highSurrogate(r[1])) + "][\\uDC00-\\uDFFF]");
            } else {
                throw new IllegalStateException(String.format("range %x-%x", r[0], r[1]));
            }
        }
        String cls = "[" + bmp + "]";
        return pairs.isEmpty() ? "/" + cls + "*/y" : "/(?:" + cls + "|" + String.join("|", pairs) + ")*/y";
    }

    public static void main(String[] args) throws Exception {
        String jdk = System.getProperty("java.vendor.version", "") + " " + System.getProperty("java.runtime.version");
        if (!"Temurin-17.0.17+10".equals(System.getProperty("java.vendor.version")) || !"17.0.17".equals(System.getProperty("java.version"))) {
            throw new IllegalStateException("need java.vendor.version Temurin-17.0.17+10 and java.version 17.0.17, got "
                    + System.getProperty("java.vendor.version") + " and " + System.getProperty("java.version"));
        }
        IntPredicate notColon = c -> c != ':';
        String out = "// Generated by tools/xml-oracle/NameTables.java from the JDK's Xerces XMLChar and XML11Char on " + jdk
            + ". Do not edit.\n"
            + "// Name start characters as inclusive code point ranges; runs of name characters other than ':'.\n"
            + "export const NAME_START_10: number[] = " + array(ranges(XMLChar::isNameStart)) + ";\n\n"
            + "export const NAME_START_11: number[] = " + array(ranges(XML11Char::isXML11NameStart)) + ";\n\n"
            + "export const NAME_RUN_10: RegExp = " + run(ranges(notColon.and(XMLChar::isName))) + ";\n\n"
            + "export const NAME_RUN_11: RegExp = " + run(ranges(notColon.and(XML11Char::isXML11Name))) + ";\n\n"
            + "export const PUBID_RUN: RegExp = " + run(ranges(XMLChar::isPubid)) + ";\n";
        Files.writeString(Path.of("oh_rome/src/main/ets/xml/XmlNameChars.ets"), out, StandardCharsets.UTF_8);
    }
}
