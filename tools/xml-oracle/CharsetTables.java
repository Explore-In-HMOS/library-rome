// Writes oh_rome/src/main/ets/xml/FormatCharsets.ets: for each JDK charset that JDOM's Format resolves through
// Charset.forName, the BMP characters its encoder can encode. From the repo root, with Temurin 17.0.17+10:
//   java tools/xml-oracle/CharsetTables.java
// Prints the charsets left out (multi-byte charsets outside MULTI_BYTE that cannot encode the whole BMP).
import java.nio.charset.Charset;
import java.nio.charset.CharsetEncoder;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

public class CharsetTables {
    static final List<String> MULTI_BYTE = List.of("GBK", "GB2312", "GB18030", "Big5", "Big5-HKSCS", "Shift_JIS",
            "windows-31j", "EUC-JP", "EUC-KR", "x-windows-949", "ISO-2022-JP");

    static boolean isSurrogate(int c) {
        return c >= 0xD800 && c <= 0xDFFF;
    }

    // Ranges of encodable BMP chars, written as base-36 "gap,length" pairs relative to the end of the previous range.
    static String table(CharsetEncoder encoder) {
        StringBuilder sb = new StringBuilder();
        int prevEnd = -1;
        int c = 0;
        while (c <= 0xFFFF) {
            if (isSurrogate(c) || !encoder.canEncode((char) c)) {
                c++;
                continue;
            }
            int start = c;
            while (c + 1 <= 0xFFFF && !isSurrogate(c + 1) && encoder.canEncode((char) (c + 1))) {
                c++;
            }
            if (sb.length() > 0) {
                sb.append(',');
            }
            sb.append(Integer.toString(start - prevEnd - 1, 36)).append(',').append(Integer.toString(c - start, 36));
            prevEnd = c;
            c++;
        }
        return sb.toString();
    }

    public static void main(String[] args) throws Exception {
        String jdk = System.getProperty("java.vendor.version", "") + " " + System.getProperty("java.runtime.version");
        if (!"Temurin-17.0.17+10".equals(System.getProperty("java.vendor.version")) || !"17.0.17".equals(System.getProperty("java.version"))) {
            throw new IllegalStateException("need java.vendor.version Temurin-17.0.17+10 and java.version 17.0.17, got "
                    + System.getProperty("java.vendor.version") + " and " + System.getProperty("java.version"));
        }
        Map<String, List<String>> namesByTable = new LinkedHashMap<>();
        List<String> skipped = new ArrayList<>();
        String fullBmp = null;
        for (Charset cs : Charset.availableCharsets().values()) {
            if (!cs.canEncode()) {
                continue;
            }
            CharsetEncoder encoder = cs.newEncoder();
            String data = table(encoder);
            if (fullBmp == null) {
                fullBmp = "0," + Integer.toString(0xD7FF, 36) + "," + Integer.toString(0x800, 36) + ","
                        + Integer.toString(0xFFFF - 0xE000, 36);
            }
            boolean singleByte = encoder.maxBytesPerChar() == 1.0f;
            if (!singleByte && !MULTI_BYTE.contains(cs.name()) && !data.equals(fullBmp)) {
                skipped.add(cs.name());
                continue;
            }
            TreeSet<String> names = new TreeSet<>();
            names.add(cs.name().toLowerCase());
            for (String alias : cs.aliases()) {
                names.add(alias.toLowerCase());
            }
            namesByTable.computeIfAbsent(data, k -> new ArrayList<>()).addAll(names);
        }
        StringBuilder out = new StringBuilder();
        out.append("// Generated by tools/xml-oracle/CharsetTables.java from the charsets of " + jdk.trim() + "; regenerate, do not edit\n");
        out.append("// Each entry: lower-cased charset names and aliases joined by '|', then the encodable BMP chars as\n");
        out.append("// base-36 'gap,length' range pairs, each gap counted from the end of the previous range.\n");
        out.append("export const CHARSET_TABLES: string[][] = [\n");
        for (Map.Entry<String, List<String>> e : namesByTable.entrySet()) {
            out.append("  ['").append(String.join("|", e.getValue())).append("', '").append(e.getKey()).append("'],\n");
        }
        out.setLength(out.length() - 2);
        out.append("\n];\n");
        Files.writeString(Path.of("oh_rome/src/main/ets/xml/FormatCharsets.ets"), out.toString());
        System.out.println("Left out: " + String.join(", ", skipped));
    }
}
