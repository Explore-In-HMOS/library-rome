package romeharmony.golden;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/** Writes one .ets per fixture (fixture text + its goldens) and the Fixtures.ets index. */
final class Emitter {

    static final String HEADER = "// Generated by tools/golden/generate.sh from ROME 6b4a7e8 test resources (Apache-2.0) on "
            + GoldenMain.jdkIdentity() + ". Do not edit.\n";
    static final String REPO_HEADER = "// Generated by tools/golden/generate.sh from ROME 6b4a7e8 run over " + GoldenMain.REPO_FIXTURES
            + " on " + GoldenMain.jdkIdentity() + ". Do not edit.\n";

    private Emitter() {
    }

    static void emit(final Path repo, final Path dumps) throws IOException {
        // fixture id -> "profile/kind" -> JSON text
        final Map<String, Map<String, String>> goldens = new TreeMap<>();
        for (final String profile : List.of("core", "opml", "full")) {
            final Path dump = dumps.resolve(profile + ".tsv");
            for (final String line : Files.readAllLines(dump)) {
                final String[] cols = line.split("\t", 3);
                goldens.computeIfAbsent(cols[0], k -> new TreeMap<>()).put(profile + "/" + cols[1], cols[2]);
            }
        }

        final Path outDir = repo.resolve("oh_rome/src/test/golden/fixtures");
        if (Files.exists(outDir)) {
            try (var old = Files.list(outDir)) {
                for (final Path p : (Iterable<Path>) old::iterator) {
                    Files.delete(p);
                }
            }
        }
        Files.createDirectories(outDir);

        final Map<String, String> moduleNames = new LinkedHashMap<>();
        for (final String line : Files.readAllLines(repo.resolve("fixtures/index.tsv"))) {
            final String id = line.split("\t")[0];
            final String name = id.replaceAll("[^A-Za-z0-9]", "_");
            if (moduleNames.containsValue(name)) {
                throw new IllegalStateException("file name collision for " + id);
            }
            moduleNames.put(id, name);
            final Map<String, String> entries = goldens.get(id);
            if (entries == null) {
                throw new IllegalStateException("no goldens for " + id);
            }
            Files.writeString(outDir.resolve(name + ".ets"),
                    fixtureFile(id, GoldenMain.fixtureText(repo.resolve("fixtures").resolve(id)), entries));
        }

        final StringBuilder index = new StringBuilder(HEADER).append("import { GoldenFixture } from './GoldenFixture';\n");
        int i = 0;
        for (final String name : moduleNames.values()) {
            index.append("import { fixture as f").append(i++).append(" } from './fixtures/").append(name).append("';\n");
        }
        index.append("\nexport const FIXTURES: GoldenFixture[] = [");
        for (int j = 0; j < i; j++) {
            index.append(j == 0 ? "" : ", ").append(j % 12 == 0 ? "\n  " : "").append('f').append(j);
        }
        index.append("\n];\n");
        Files.writeString(repo.resolve("oh_rome/src/test/golden/Fixtures.ets"), index.toString());
        System.out.println("emitted " + i + " fixture files");
    }

    // Identical goldens (e.g. a rome fixture under "core" and "full") are stored once and referenced by index.
    private static String fixtureFile(final String id, final String text, final Map<String, String> entries) {
        final List<String> values = new ArrayList<>();
        final Map<String, Integer> valueIndex = new HashMap<>();
        final StringBuilder keys = new StringBuilder();
        final StringBuilder refs = new StringBuilder();
        for (final Map.Entry<String, String> e : entries.entrySet()) {
            final int idx = valueIndex.computeIfAbsent(e.getValue(), v -> {
                values.add(v);
                return values.size() - 1;
            });
            keys.append(keys.length() == 0 ? "" : ", ").append(literal(e.getKey()));
            refs.append(refs.length() == 0 ? "" : ", ").append(idx);
        }
        final StringBuilder sb = new StringBuilder(id.startsWith("repo/") ? REPO_HEADER : HEADER)
                .append("import { GoldenFixture } from '../GoldenFixture';\n\n");
        sb.append("export const fixture: GoldenFixture = new GoldenFixture(\n  ").append(literal(id)).append(",\n  ")
                .append(literal(text)).append(",\n  [").append(keys).append("],\n  [").append(refs).append("],\n  [");
        for (int i = 0; i < values.size(); i++) {
            sb.append(i == 0 ? "\n    " : ",\n    ").append(literal(values.get(i)));
        }
        sb.append("\n  ]\n);\n");
        return sb.toString();
    }

    // A single-quoted ArkTS string literal.
    static String literal(final String s) {
        final StringBuilder sb = new StringBuilder("'");
        for (int i = 0; i < s.length(); i++) {
            final char c = s.charAt(i);
            switch (c) {
                case '\'':
                    sb.append("\\'");
                    break;
                case '\\':
                    sb.append("\\\\");
                    break;
                case '\n':
                    sb.append("\\n");
                    break;
                case '\r':
                    sb.append("\\r");
                    break;
                case '\t':
                    sb.append("\\t");
                    break;
                default:
                    if (c < 0x20 || c == 0x2028 || c == 0x2029 || c == 0x7f || Character.isSurrogate(c)) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
            }
        }
        return sb.append('\'').toString();
    }
}
