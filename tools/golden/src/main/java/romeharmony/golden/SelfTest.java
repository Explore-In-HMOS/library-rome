import java.nio.file.Path;
import java.util.Date;
import java.util.List;

/**
 * Goldens for objects built by hand instead of parsed, so the harness can be checked before any parser exists.
 * oh_rome/src/test/GoldenHarness.test.ets builds exactly the same objects with our classes.
 */
final class SelfTest {

    private SelfTest() {
    }

    static SyndFeed syndFeed() {
        final SyndFeed feed = new SyndFeedImpl();
        feed.setFeedType("rss_2.0");
        feed.setTitle("Feed & title");
        feed.setDescription("Feed description");
        feed.setLink("http://example.com/");
        feed.setUri("urn:feed");
        feed.setPublishedDate(new Date(1700000000123L));
        feed.setLanguage("tr");
        feed.setAuthor("Feed author");
        feed.setCopyright("(c) 2026");
        final SyndCategory feedCategory = new SyndCategoryImpl();
        feedCategory.setName("news");
        feedCategory.setTaxonomyUri("urn:tax");
        feed.setCategories(List.of(feedCategory));
        final SyndImage image = new SyndImageImpl();
        image.setTitle("Logo");
        image.setUrl("http://example.com/logo.png");
        image.setWidth(88);
        feed.setImage(image);

        final SyndEntry entry = new SyndEntryImpl();
        entry.setTitle("Entry title");
        entry.setLink("http://example.com/1");
        entry.setUri("urn:entry:1");
        entry.setPublishedDate(new Date(1700000001000L));
        entry.setUpdatedDate(new Date(1700000002000L));
        final SyndContent description = new SyndContentImpl();
        description.setType("text/html");
        description.setValue("<b>bold</b>");
        entry.setDescription(description);
        final SyndContent content = new SyndContentImpl();
        content.setType("text/plain");
        content.setValue("Body");
        entry.setContents(List.of(content));
        final SyndEnclosure enclosure = new SyndEnclosureImpl();
        enclosure.setUrl("http://example.com/a.mp3");
        enclosure.setType("audio/mpeg");
        enclosure.setLength(12345L);
        entry.setEnclosures(List.of(enclosure));
        final SyndPerson person = new SyndPersonImpl();
        person.setName("Ada");
        person.setEmail("ada@example.com");
        entry.setAuthors(List.of(person));
        final SyndLink link = new SyndLinkImpl();
        link.setHref("http://example.com/alt");
        link.setRel("alternate");
        link.setLength(7L);
        entry.setLinks(List.of(link));
        final SyndCategory entryCategory = new SyndCategoryImpl();
        entryCategory.setName("tech");
        entry.setCategories(List.of(entryCategory));
        final Element markup = new Element("extra", Namespace.getNamespace("x", "urn:x"));
        markup.setAttribute("a", "1 < 2");
        markup.setText("text & more");
        entry.setForeignMarkup(List.of(markup));
        feed.setEntries(List.of(entry));
        return feed;
    }

    static void emit(final Path repo) throws IOException {
        final String json = Json.write(new BeanJson().value(syndFeed()));
        Files.writeString(repo.resolve("oh_rome/src/test/golden/SelfTestGoldens.ets"),
                "// Generated by tools/golden/generate.sh (SelfTest.java) with ROME 6b4a7e8 on " + GoldenMain.jdkIdentity()
                        + ". Do not edit.\n"
                        + "export const SELF_TEST_SYND_FEED: string = " + Emitter.literal(json) + ";\n");
    }
}
