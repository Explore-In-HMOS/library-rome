// Writes oh_rome/src/main/ets/io/JavaCharsets.ets: every charset name and alias that JDK 17's Charset.forName accepts, and
// the 256-char decode table of each single-byte charset (bytes Java can't map decode to U+FFFD).
// Usage (from the repo root, Temurin 17.0.17+10): java tools/xmlreader-oracle/JavaCharsets.java
import java.nio.charset.Charset;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeSet;

public class JavaCharsets {
    // A charset is single-byte when every byte and every pair of bytes decodes byte by byte.
    static String table(Charset cs) {
        StringBuilder t = new StringBuilder();
        for (int b = 0; b < 256; b++) {
            String s = new String(new byte[] { (byte) b }, cs);
            if (s.length() != 1) return null;
            t.append(s);
        }
        byte[] pair = new byte[2];
        for (int x = 0; x < 256; x++) {
            for (int y = 0; y < 256; y++) {
                pair[0] = (byte) x;
                pair[1] = (byte) y;
                String s = new String(pair, cs);
                if (s.length() != 2 || s.charAt(0) != t.charAt(x) || s.charAt(1) != t.charAt(y)) return null;
            }
        }
        return t.toString();
    }

    static String q(String s) {
        StringBuilder b = new StringBuilder("'");
        for (char c : s.toCharArray()) {
            if (c == '\'' || c == '\\') b.append('\\').append(c);
            else if (c < 0x20 || c > 0x7e) b.append(String.format("\\u%04X", (int) c));
            else b.append(c);
        }
        return b.append("'").toString();
    }

    public static void main(String[] args) throws Exception {
        String jdk = System.getProperty("java.vendor.version", "") + " " + System.getProperty("java.runtime.version");
        if (!"Temurin-17.0.17+10".equals(System.getProperty("java.vendor.version")) || !"17.0.17".equals(System.getProperty("java.version"))) {
            throw new IllegalStateException("need java.vendor.version Temurin-17.0.17+10 and java.version 17.0.17, got "
                    + System.getProperty("java.vendor.version") + " and " + System.getProperty("java.version"));
        }
        List<String> tables = new ArrayList<>();
        StringBuilder out = new StringBuilder();
        out.append("// Generated by tools/xmlreader-oracle/JavaCharsets.java on ").append(jdk.trim()).append(". Do not edit.\n");
        out.append("export interface JavaCharset {\n  name: string;\n  // Index into SINGLE_BYTE_TABLES, -1 for a multi-byte charset.\n")
                .append("  table: number;\n  aliases: string[];\n}\n\n");
        out.append("export const JAVA_CHARSETS: JavaCharset[] = [\n");
        for (Charset cs : Charset.availableCharsets().values()) {
            String t = table(cs);
            int index = -1;
            if (t != null) {
                index = tables.indexOf(t);
                if (index == -1) {
                    tables.add(t);
                    index = tables.size() - 1;
                }
            }
            List<String> aliases = new ArrayList<>();
            for (String a : new TreeSet<>(cs.aliases())) aliases.add(q(a));
            out.append("  { name: ").append(q(cs.name())).append(", table: ").append(index).append(", aliases: [")
                    .append(String.join(", ", aliases)).append("] },\n");
        }
        out.append("];\n\nexport const SINGLE_BYTE_TABLES: string[] = [\n");
        for (String t : tables) out.append("  ").append(q(t)).append(",\n");
        out.append("];\n");
        Files.writeString(Path.of("oh_rome/src/main/ets/io/JavaCharsets.ets"), out);
    }
}
