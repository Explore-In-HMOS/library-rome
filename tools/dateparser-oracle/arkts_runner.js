// Runs the ArkTS port of DateParser, Base64 and NumberParser over a cases file under Node, writing results in
// RomeOracle.java's format. It transpiles DateParser.ets, Base64.ets, NumberParser.ets and their relative
// imports with the TypeScript compiler bundled with DevEco Studio (or the one in $TYPESCRIPT) into <work>/js.
// Node is not the ArkTS runtime: this cannot see bugs of the ArkTS runtime itself (its Number(string), for one,
// misrounds some decimals). --emit-test covers that: it writes a hypium test with every case whose Node result
// equals Java's, to be run once inside the ArkTS runtime by registering it in List.test.ets temporarily.
// Usage (from the repo root; DPZ is the port's default zone, TZ must be the same zone for 'local'):
//   DPZ=UTC TZ=UTC node tools/dateparser-oracle/arkts_runner.js <cases file> <output file> <work dir>
//   DPZ=local TZ=America/New_York node tools/dateparser-oracle/arkts_runner.js <cases> <output> <work dir>
//   node tools/dateparser-oracle/arkts_runner.js --emit-test <out .test.ets> <cases> <java> <node results> ...
//     (UTC results only; the test pins the port to UTC)
'use strict';
const fs = require('fs');
const path = require('path');
const ts = require(process.env.TYPESCRIPT ||
  '/Applications/DevEco-Studio.app/Contents/tools/hvigor/hvigor/node_modules/typescript');

const SRC = path.resolve(__dirname, '../../oh_rome/src/main/ets');
const ENTRIES = ['io/impl/DateParser.ets', 'io/impl/Base64.ets', 'io/impl/NumberParser.ets'];

function transpile(outDir) {
  const pending = ENTRIES.slice();
  const done = new Set();
  while (pending.length > 0) {
    const rel = pending.pop();
    if (done.has(rel)) {
      continue;
    }
    done.add(rel);
    const source = fs.readFileSync(path.join(SRC, rel), 'utf8');
    for (const m of source.matchAll(/from '(\.{1,2}\/[^']+)'/g)) {
      pending.push(path.normalize(path.join(path.dirname(rel), m[1] + '.ets')));
    }
    const js = ts.transpileModule(source, {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 }
    }).outputText;
    const out = path.join(outDir, rel.replace(/\.ets$/, '.js'));
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, js);
  }
}

function unescape(s) {
  return s.replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

function escape(s) {
  let out = '';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    out += c < 0x20 || c > 0x7e || c === 0x5c ? '\\u' + c.toString(16).padStart(4, '0') : s.charAt(i);
  }
  return out;
}

function floatBits(f) {
  const view = new DataView(new ArrayBuffer(4));
  view.setFloat32(0, f);
  return view.getUint32(0).toString(16).padStart(8, '0');
}

// Writes a hypium test (exported function oracleCorpusTest) over the given (cases, java, node) file triples.
function emitTest(outFile, triples) {
  const rows = [];
  for (let i = 0; i < triples.length; i += 3) {
    const cases = fs.readFileSync(triples[i], 'utf8').split('\n').filter((l) => l.length > 0);
    const java = fs.readFileSync(triples[i + 1], 'utf8').split('\n');
    const node = fs.readFileSync(triples[i + 2], 'utf8').split('\n');
    cases.forEach((line, k) => {
      if (java[k] === node[k]) {
        rows.push(line + '\t' + java[k]);
      }
    });
  }
  const quote = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
  const chunks = [];
  for (let i = 0; i < rows.length; i += 2000) {
    chunks.push('const CASES_' + chunks.length + ': string[] = [\n' + rows.slice(i, i + 2000).map((r) => '  ' + quote(r))
      .join(',\n') + '\n];\n');
  }
  const all = chunks.map((_, k) => 'CASES_' + k).join(', ');
  fs.writeFileSync(outFile, `// Generated by tools/dateparser-oracle/arkts_runner.js --emit-test. Do not commit or register permanently.
import { describe, expect, it } from '@ohos/hypium';
import { Base64 } from '../main/ets/io/impl/Base64';
import { DateParser } from '../main/ets/io/impl/DateParser';
import { NumberParser } from '../main/ets/io/impl/NumberParser';

${chunks.join('\n')}
function unescape(s: string): string {
  return s.replace(/\\\\u([0-9a-f]{4})/g, (m: string, h: string) => String.fromCharCode(parseInt(h, 16)));
}

function escape(s: string): string {
  let out = '';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    out += c < 0x20 || c > 0x7e || c === 0x5c ? '\\\\u' + c.toString(16).padStart(4, '0') : s.charAt(i);
  }
  return out;
}

function bits(value: number): string {
  const view = new DataView(new ArrayBuffer(4));
  view.setFloat32(0, value);
  return view.getUint32(0).toString(16).padStart(8, '0');
}

function run(kind: string, arg: string, input: string): string {
  try {
    if (kind === 'P' || kind === 'W' || kind === 'R') {
      DateParser.setExtraMasks(arg === '' ? [] : arg.split('|'));
      const d = kind === 'P' ? DateParser.parseDate(input) :
        (kind === 'W' ? DateParser.parseW3CDateTime(input) : DateParser.parseRFC822(input));
      return d === null ? 'null' : String(d.getTime());
    }
    if (kind === 'F') {
      const d = new Date(Number(BigInt(input)));
      return DateParser.formatRFC822(d) + ' / ' + DateParser.formatW3CDateTime(d);
    }
    if (kind === 'B64D') {
      return escape(Base64.decode(input));
    }
    if (kind === 'B64E') {
      return escape(Base64.encode(input));
    }
    if (kind === 'LONG') {
      const v = NumberParser.parseLong(input);
      return v === null ? 'null' : BigInt(v).toString();
    }
    if (kind === 'INT') {
      const v = NumberParser.parseInt(input);
      return v === null ? 'null' : String(v);
    }
    const f = NumberParser.parseFloat(input);
    return f === null ? 'null' : bits(f);
  } catch (e) {
    return 'EXC ' + escape(String((e as Error).message));
  }
}

export default function oracleCorpusTest() {
  describe('OracleCorpus', () => {
    it('matchesJava', 0, () => {
      const timeZone = DateParser.getDefaultTimeZone();
      DateParser.setDefaultTimeZone('UTC');
      const failures: string[] = [];
      let count = 0;
      for (const cases of [${all}]) {
        for (const row of cases) {
          const f = row.split('\\t');
          const actual = run(f[0], unescape(f[1]), unescape(f[2]));
          count++;
          if (actual !== f[3] && failures.length < 50) {
            failures.push(row + ' -> ' + actual);
          }
        }
      }
      DateParser.setExtraMasks([]);
      DateParser.setDefaultTimeZone(timeZone);
      expect(count + ' cases; mismatches: ' + failures.join(' | ')).assertEqual(count + ' cases; mismatches: ');
    });
  });
}
`);
  console.log('wrote ' + rows.length + ' cases to ' + outFile);
}

function main() {
  if (process.argv[2] === '--emit-test') {
    emitTest(process.argv[3], process.argv.slice(4));
    return;
  }
  const [casesFile, outFile, workDir] = process.argv.slice(2);
  const jsDir = path.join(workDir, 'js');
  transpile(jsDir);
  const { DateParser } = require(path.join(jsDir, 'io/impl/DateParser.js'));
  const { Base64 } = require(path.join(jsDir, 'io/impl/Base64.js'));
  const { NumberParser } = require(path.join(jsDir, 'io/impl/NumberParser.js'));
  DateParser.setDefaultTimeZone(process.env.DPZ || 'UTC');
  const lines = fs.readFileSync(casesFile, 'utf8').split('\n').filter((l) => l.length > 0);
  const results = lines.map((line) => {
    const [kind, rawArg, rawInput] = line.split('\t');
    const arg = unescape(rawArg);
    const input = unescape(rawInput);
    try {
      switch (kind) {
        case 'P': case 'W': case 'R': {
          DateParser.setExtraMasks(arg === '' ? [] : arg.split('|'));
          const d = kind === 'P' ? DateParser.parseDate(input) :
            kind === 'W' ? DateParser.parseW3CDateTime(input) : DateParser.parseRFC822(input);
          return d === null ? 'null' : String(d.getTime());
        }
        case 'F': {
          const d = new Date(Number(input));
          return DateParser.formatRFC822(d) + ' / ' + DateParser.formatW3CDateTime(d);
        }
        case 'B64D': return escape(Base64.decode(input));
        case 'B64E': return escape(Base64.encode(input));
        case 'LONG': {
          const v = NumberParser.parseLong(input);
          return v === null ? 'null' : BigInt(v).toString();
        }
        case 'INT': {
          const v = NumberParser.parseInt(input);
          return v === null ? 'null' : String(v);
        }
        case 'FLOAT': {
          const v = NumberParser.parseFloat(input);
          return v === null ? 'null' : floatBits(v);
        }
        default: throw new Error('unknown kind ' + kind);
      }
    } catch (e) {
      return 'EXC ' + escape(String(e.message));
    }
  });
  fs.writeFileSync(outFile, results.join('\n') + '\n');
}

main();
