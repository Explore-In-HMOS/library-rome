import java.io.*; import java.nio.charset.StandardCharsets; import java.text.*; import java.util.*;

// Writes oh_rome/src/main/ets/io/impl/DateParserZoneNames.ets from DateFormatSymbols(Locale.US).getZoneStrings()
// and prints the other JDK data DateParser.ets hard-codes (month, weekday and AM/PM names, DecimalFormat symbols)
// so they can be compared by eye. Refuses to run on anything but Temurin 17.0.17+10.
// Usage (from the repo root):
//   <Temurin 17.0.17+10>/bin/java -Duser.language=en -Duser.country=US tools/dateparser-oracle/GenZoneNames.java
public class GenZoneNames {
  public static void main(String[] a) throws Exception {
    String target = a.length > 0 ? a[0] : "oh_rome/src/main/ets/io/impl/DateParserZoneNames.ets";
    String version = System.getProperty("java.runtime.version");
    if (!"Temurin-17.0.17+10".equals(System.getProperty("java.vendor.version")) || !"17.0.17".equals(System.getProperty("java.version"))) {
        throw new IllegalStateException("need java.vendor.version Temurin-17.0.17+10 and java.version 17.0.17, got "
                + System.getProperty("java.vendor.version") + " and " + System.getProperty("java.version"));
    }
    DateFormatSymbols sym = DateFormatSymbols.getInstance(Locale.US);
    System.out.println("months=" + Arrays.toString(sym.getMonths()));
    System.out.println("shortMonths=" + Arrays.toString(sym.getShortMonths()));
    System.out.println("weekdays=" + Arrays.toString(sym.getWeekdays()));
    System.out.println("shortWeekdays=" + Arrays.toString(sym.getShortWeekdays()));
    System.out.println("amPm=" + Arrays.toString(sym.getAmPmStrings()));
    DecimalFormatSymbols dfs = DecimalFormatSymbols.getInstance(Locale.US);
    System.out.println("NaN=" + dfs.getNaN() + " infinity=" + dfs.getInfinity() + " minus=" + dfs.getMinusSign() + " exponent=" + dfs.getExponentSeparator() + " zero=" + dfs.getZeroDigit());
    String[][] zones = sym.getZoneStrings();
    List<String> seen = new ArrayList<>(); List<String> entries = new ArrayList<>();
    for (String[] r : zones) {
      TimeZone tz = TimeZone.getTimeZone(r[0]);
      int raw = tz.getRawOffset(), dst = tz.getDSTSavings();
      if (raw % 60000 != 0 || dst % 60000 != 0) throw new IllegalStateException(r[0]);
      for (int i = 1; i <= 4; i++) {
        String n = r[i];
        if (n == null || n.isEmpty()) throw new IllegalStateException("empty name in " + r[0]);
        String ln = n.toLowerCase(Locale.ROOT);
        boolean shadowed = false;
        for (String s : seen) if (ln.startsWith(s)) { shadowed = true; break; }
        if (shadowed) continue;
        seen.add(ln);
        boolean same = i <= 2 && n.equalsIgnoreCase(r[i + 2]);
        boolean decides = same || (i >= 3 && dst == 0);
        if (n.contains(",") || n.contains(";")) throw new IllegalStateException(n);
        entries.add(n + "," + raw / 60000 + "," + (decides ? "*" : String.valueOf(i >= 3 ? dst / 60000 : 0)));
      }
    }
    StringBuilder out = new StringBuilder();
    out.append("// Generated by tools/dateparser-oracle/GenZoneNames.java on Temurin ").append(version)
        .append(", data for the port of ROME rome/src/main/java/com/rometools/rome/io/impl/DateParser.java (Apache-2.0)\n");
    out.append("// Source: DateFormatSymbols(Locale.US).getZoneStrings(). Do not edit.\n");
    out.append("// Flattened in lookup order as \"name,raw,dst\" with offsets in minutes. Names that can never win (a name or\n");
    out.append("// prefix of it appeared earlier) are left out. dst \"*\" means the zone's own rules decide; this port uses the\n");
    out.append("// zone's current raw offset without DST then.\n");
    out.append("export const ZONE_NAMES: string =\n");
    List<String> lines = new ArrayList<>(); StringBuilder cur = new StringBuilder();
    for (String e : entries) {
      String esc = e.replace("\\", "\\\\").replace("'", "\\'");
      if (cur.length() + esc.length() + 1 > 100) { lines.add(cur.toString()); cur.setLength(0); }
      cur.append(esc).append(';');
    }
    String last = cur.toString(); lines.add(last.substring(0, last.length() - 1));
    for (int i = 0; i < lines.size(); i++) out.append("  '").append(lines.get(i)).append("'").append(i < lines.size() - 1 ? " +\n" : ";\n");
    try (Writer w = new OutputStreamWriter(new FileOutputStream(target), StandardCharsets.UTF_8)) { w.write(out.toString()); }
    System.out.println("zones=" + zones.length + " entries=" + entries.size());
  }
}
