// Writes oh_rome/src/test/DoubleStringCases.ets: the raw bits of each double below and Java's Double.toString of it.
// Usage (from the repo root, with the JDK 17 the goldens use): java tools/jdk-oracle/DoubleStringOracle.java
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashSet;
import java.util.Locale;
import java.util.Random;
import java.util.Set;

public class DoubleStringOracle {
    static final String[] FIXED = {
        // realistic coordinates JDK 17 prints shorter than the runtime's toExponential() and String()
        "35.09239818", "37.99687960292", "63.89980610824745",
        // JDK 17 is not shortest-digit (JDK-4511638)
        "5.997623033256369e+18", "2.82879384806159E17", "1.387364135037754E18", "1.45800632428665E17", "1.0E23", "2.0E23",
        // Subnormals and range edges
        "4.9E-324", "1.0E-323", "2.2250738585072014E-308", "2.225073858507201E-308", "1.7976931348623157E308",
        // Layout boundaries: plain for 1e-3 <= |v| < 1e7
        "0.001", "9.999999999999999E-4", "1.0E7", "9999999.999999998", "1.0E-5", "1.0E21", "1.0E22",
        // Integers, zeros, signs
        "0.0", "-0.0", "1.0", "-1.0", "100", "-45.5", "0.1", "0.3", "123456789012345678", "9.223372036854776E18",
        "NaN", "Infinity", "-Infinity",
    };

    public static void main(String[] args) throws Exception {
        // Every oracle and the goldens run on this JDK (URL, Currency and charset data differ between JDKs).
        if (!"Temurin-17.0.17+10".equals(System.getProperty("java.vendor.version")) || !"17.0.17".equals(System.getProperty("java.version"))) {
            throw new IllegalStateException("need java.vendor.version Temurin-17.0.17+10 and java.version 17.0.17, got "
                    + System.getProperty("java.vendor.version") + " and " + System.getProperty("java.version"));
        }
        Set<Long> bits = new LinkedHashSet<>();
        for (String s : FIXED) bits.add(Double.doubleToRawLongBits(Double.parseDouble(s)));
        Random r = new Random(86);
        // Coordinates as feeds write them: 1 to 15 decimals, latitude and longitude ranges
        for (int i = 0; i < 3000; i++) {
            double range = i % 2 == 0 ? 180 : 360;
            String s = String.format(Locale.ROOT, "%." + (1 + r.nextInt(15)) + "f", r.nextDouble() * range - range / 2);
            bits.add(Double.doubleToRawLongBits(Double.parseDouble(s)));
        }
        for (int i = 0; i < 500; i++) bits.add(r.nextLong());
        for (int i = 0; i < 300; i++) bits.add(1L + r.nextInt(1 << 20) * (r.nextInt(3) == 0 ? 1L : 1L << r.nextInt(32)));
        for (int i = 0; i < 300; i++) bits.add(Double.doubleToRawLongBits((double) (r.nextLong() >>> r.nextInt(64))));
        StringBuilder out = new StringBuilder("// Generated by tools/jdk-oracle/DoubleStringOracle.java on JDK "
            + System.getProperty("java.version") + ". Do not edit.\n// Raw bits (hex) and Double.toString.\n"
            + "export const DOUBLE_STRING_CASES: string[][] = [\n");
        int n = 0;
        for (long b : bits) {
            double d = Double.longBitsToDouble(b);
            if (Double.isNaN(d) && b != Double.doubleToRawLongBits(Double.NaN)) continue;
            out.append("  ['").append(String.format("%016x", b)).append("', '").append(Double.toString(d)).append("'],\n");
            n++;
        }
        out.append("];\n");
        Files.writeString(Path.of("oh_rome/src/test/DoubleStringCases.ets"), out.toString(), StandardCharsets.UTF_8);
        System.out.println(n + " cases");
    }
}
